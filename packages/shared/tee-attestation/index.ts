/**
 * A test vector representing an adversarial attestation scenario.
 */
export interface AdversarialScenario {
  description: string;
  expectedFailureCode: AttestationFailureCode;
  /** A valid base document (returned by `buildBaseDocument`) with the
   *  mutation applied that triggers the failure. */
  document: NitroAttestationDocument;
}

/**
 * Build a base valid attestation document for testing.
 */
export function buildBaseDocument(overrides?: Partial<NitroAttestationDocument>): NitroAttestationDocument {
  return {
    documentId: "doc-test-001",
    moduleId: "nitro-nsm-v1",
    timestamp: new Date().toISOString(),
    enclaveImageHash: "approved-hash-abc123",
    pcr: {
      pcr0: "approved-pcr0-aaa",
      pcr1: "approved-pcr1-bbb",
      pcr2: "approved-pcr2-ccc",
    },
    certificate: "valid-cert-chain-pem",
    publicKey: "registered-provider-pubkey-hex",
    nonce: "expected-nonce-xyz",
    userData: hexEncode("job-id-001"),
    signature: "valid-signature-base64",
    ...overrides,
  };
}

/**
 * Generate adversarial test scenarios for each `AttestationFailureCode`.
 *
 * Use these in unit and integration tests to verify the pipeline rejects
 * malicious or malformed inputs under all documented failure modes.
 */
export function buildAdversarialScenarios(): AdversarialScenario[] {
  return [
    {
      description: "Empty documentId causes document_malformed",
      expectedFailureCode: "document_malformed",
      document: buildBaseDocument({ documentId: "" }),
    },
    {
      description: "Stale timestamp causes staleness_exceeded",
      expectedFailureCode: "staleness_exceeded",
      document: buildBaseDocument({
        timestamp: new Date(Date.now() - 3_600_000).toISOString(), // 1 hour ago
      }),
    },
    {
      description: "Wrong nonce causes nonce_mismatch",
      expectedFailureCode: "nonce_mismatch",
      document: buildBaseDocument({ nonce: "wrong-nonce" }),
    },
    {
      description: "Wrong userData causes user_data_mismatch",
      expectedFailureCode: "user_data_mismatch",
      document: buildBaseDocument({ userData: hexEncode("wrong-job-id") }),
    },
    {
      description: "Unknown PCR0 causes pcr_mismatch",
      expectedFailureCode: "pcr_mismatch",
      document: buildBaseDocument({
        pcr: {
          pcr0: "unknown-pcr0-zzz",
          pcr1: "approved-pcr1-bbb",
          pcr2: "approved-pcr2-ccc",
        },
      }),
    },
    {
      description: "Unapproved code hash causes code_hash_not_approved",
      expectedFailureCode: "code_hash_not_approved",
      document: buildBaseDocument({ enclaveImageHash: "unapproved-hash-xyz" }),
    },
    {
      description: "Unregistered provider key causes public_key_not_registered",
      expectedFailureCode: "public_key_not_registered",
      document: buildBaseDocument({ publicKey: "unregistered-key-hex" }),
    },
  ];
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function hexEncode(input: string): string {
  return Array.from(new TextEncoder().encode(input))
    .map((b) => b.toString(16).padStart(2, "0"))
    .join("");
}

function hexDecode(hex: string): string {
  if (hex.length % 2 !== 0) throw new Error("Invalid hex string");
  const bytes: number[] = [];
  for (let i = 0; i < hex.length; i += 2) {
    bytes.push(parseInt(hex.slice(i, i + 2), 16));
  }
  return new TextDecoder().decode(new Uint8Array(bytes));
}
