export type AttestationAlertSeverity = "info" | "warning" | "critical";

/**
 * A structured alert record for operator notification systems.
 */
export interface AttestationAdminAlert {
  alertId: string;
  severity: AttestationAlertSeverity;
  title: string;
  message: string;
  failureCode: AttestationFailureCode;
  documentId: string;
  /** Operator action recommended in response to this alert. */
  recommendedAction: string;
  generatedAt: string;
}

/**
 * Convert a failed attestation result into a structured admin alert.
 *
 * Returns `null` if the result was accepted (no alert needed).
 */
export function buildAdminAlert(
  result: AttestationValidationResult
): AttestationAdminAlert | null {
  if (result.accepted || !result.primaryFailureCode) return null;

  const failureCode = result.primaryFailureCode;
  const severity = ALERT_SEVERITY_MAP[failureCode] ?? "warning";

  return {
    alertId: `alert-${result.documentId}-${new Date(result.validatedAt).getTime()}`,
    severity,
    title: `Attestation Validation Failure: ${failureCode}`,
    message: result.summary,
    failureCode,
    documentId: result.documentId,
    recommendedAction: RECOMMENDED_ACTIONS[failureCode],
    generatedAt: result.validatedAt,
  };
}

const ALERT_SEVERITY_MAP: Record<
  AttestationFailureCode,
  AttestationAlertSeverity
> = {
  document_malformed: "warning",
  signature_invalid: "critical",
  certificate_invalid: "critical",
  pcr_mismatch: "critical",
  code_hash_not_approved: "critical",
  nonce_mismatch: "critical",
  staleness_exceeded: "warning",
  user_data_mismatch: "warning",
  public_key_not_registered: "critical",
  platform_state_invalid: "critical",
  unknown_module: "warning",
};

const RECOMMENDED_ACTIONS: Record<AttestationFailureCode, string> = {
  document_malformed:
    "Inspect the raw attestation document from the oracle node logs. Check for truncation or encoding issues.",
  signature_invalid:
    "The attestation signature is invalid. Suspend the provider immediately and audit recent attestations. Contact the oracle operator.",
  certificate_invalid:
    "The enclave certificate chain is invalid or expired. Rebuild the enclave image and re-register the new code hash.",
  pcr_mismatch:
    "PCR measurements do not match approved values. The enclave image may have been replaced. Suspend the provider and audit the enclave build pipeline.",
  code_hash_not_approved:
    "Register the new enclave code hash in contracts/registry before accepting attestations, or reject if the image is unexpected.",
  nonce_mismatch:
    "Possible replay or substitution attack. Reject the attestation and notify the security team.",
  staleness_exceeded:
    "The attestation document is stale. Ensure oracle node clocks are synchronised and the attestation is generated close to submission time.",
  user_data_mismatch:
    "The attestation is not bound to the expected verification job. Reject the attestation to prevent misapplication.",
  public_key_not_registered:
    "Register the oracle provider key in contracts/oracle.register_provider before accepting attestations.",
  platform_state_invalid:
    "The enclave platform state is inconsistent. Suspend the provider and investigate the hardware environment.",
  unknown_module:
    "The attestation originates from an unrecognised module ID. Verify the oracle node configuration.",
};

